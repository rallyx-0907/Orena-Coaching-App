"""``apply-feedback`` (human, 2026-09-29, item 4): fold external-review feedback back into a level.

Input: several JSONL files of one level (``review_export.py`` says what a reviewer returns). Steps:

1. **Parse** each line (code fences and blank lines tolerated; a line that is not a JSON object with
   the five keys is recorded as unparsed, never fatal). ``block: "none"`` lines are the reviewer's
   "ok" markers and are dropped.
2. **De-duplicate**: feedback on the same point and block from different reviewers (or the same one
   twice) that says the same thing collapses into one item; the highest severity and every source
   are kept.
3. **Apply** per point and block: the flagged block alone is regenerated by the model from the
   current block plus the feedback (same schemas and assembly as ``generate``), written into a
   copy, and the whole set is validated again. A block whose regeneration introduces a validate
   issue is put back and reported as skipped with the codes. Feedback about the level as a whole,
   about a point's structural metadata, or about an approved point is left to the human.
4. **Log** which feedback was applied and which skipped, with the reason, to
   ``grammar_lab/review/<lang>/<level>.applied.json``.

Never sets ``status``: a point that took feedback stays what it was (a draft), and only a human
approves.
"""

