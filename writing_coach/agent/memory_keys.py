"""The memory key: keyed HMACs of a memory's slot and value (ORENA_MEMORY.md rev 4.1 §4.1; D-222).

A stored memory carries `value_key` = HMAC-SHA256(secret, slot + value) and the `key_version` of the secret, for
dedupe and for suppression keys, which hold no text: a short, low-entropy value cannot be recovered from the key by
guessing without the secret.

`AGENT_MEMORY_HMAC_KEYS` lists versioned secrets, `v1:<secret>` and after a rotation `v1:<old>,v2:<new>`; the highest
version is current. Each secret is generated once per environment and kept across deploys and restarts; it is never
regenerated by a deploy. No key means memory is off (fail closed): `from_env` returns None, and nothing is read or
written. A lookup computes the HMAC under every configured version, so rows written before a rotation still dedupe
and still suppress. Rotation is an explicit maintenance operation (re-key live rows from their text; suppression keys
keep their version until they expire), and `check_in_use` refuses a configuration that drops a version still used.
"""

from __future__ import annotations

import hashlib
import hmac
import re
import unicodedata
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from types import MappingProxyType
from typing import Any

MIN_SECRET = 32  # characters; a generated secret (for example `secrets.token_urlsafe(32)`) is 43
_ENTRY = re.compile(r"^v(?P<version>[1-9][0-9]{0,3}):(?P<secret>\S+)$")
_SPACE = re.compile(r"\s+")
_SEPARATOR = "\x1f"  # between slot and value; removed from both, so no two pairs share a message


def normalise(text: str | None) -> str:
    """The form a value is keyed and compared in: NFC, case-folded, whitespace collapsed, trimmed."""

    folded = unicodedata.normalize("NFC", text or "").casefold().replace(_SEPARATOR, " ")
    return _SPACE.sub(" ", folded).strip()


@dataclass(frozen=True)
class MemoryKeys:
    secrets: Mapping[int, bytes] = field(repr=False)  # never printed

    def __post_init__(self) -> None:
        if not self.secrets:
            raise ValueError("a memory key set needs at least one version")

    @property
    def current(self) -> int:
        return max(self.secrets)

    def value_key(self, slot: str, value: str, version: int | None = None) -> str:
        version = self.current if version is None else version
        message = f"{normalise(slot)}{_SEPARATOR}{normalise(value)}".encode()
        return hmac.new(self.secrets[version], message, hashlib.sha256).hexdigest()

    def stamp(self, slot: str, value: str) -> tuple[int, str]:
        """(`key_version`, `value_key`) for a new row: always the current version."""

        return self.current, self.value_key(slot, value)

    def candidates(self, slot: str, value: str) -> dict[int, str]:
        """The key under every configured version: a row of version v matches if its `value_key` is `[v]`."""

        return {version: self.value_key(slot, value, version) for version in sorted(self.secrets)}

    def matches(self, slot: str, value: str, key_version: int, value_key: str) -> bool:
        if key_version not in self.secrets:
            return False
        return hmac.compare_digest(self.value_key(slot, value, key_version), value_key)

    def check_in_use(self, versions: Iterable[int]) -> None:
        """Refuse to start when a stored row or an unexpired suppression key uses a version not configured."""

        missing = sorted(set(versions) - set(self.secrets))
        if missing:
            raise ValueError(f"AGENT_MEMORY_HMAC_KEYS is missing version(s) still in use: {missing}")

    @classmethod
    def parse(cls, text: str | None) -> MemoryKeys | None:
        secrets: dict[int, bytes] = {}
        for entry in (text or "").split(","):
            entry = entry.strip()
            if not entry:
                continue
            found = _ENTRY.match(entry)
            if not found:
                raise ValueError("AGENT_MEMORY_HMAC_KEYS entries are v<version>:<secret>")
            version, secret = int(found["version"]), found["secret"]
            if version in secrets:
                raise ValueError(f"AGENT_MEMORY_HMAC_KEYS names v{version} twice")
            if len(secret) < MIN_SECRET:
                raise ValueError(f"AGENT_MEMORY_HMAC_KEYS v{version} is shorter than {MIN_SECRET} characters")
            secrets[version] = secret.encode()
        return cls(MappingProxyType(secrets)) if secrets else None

    @classmethod
    def from_env(cls, environ: Mapping[str, Any]) -> MemoryKeys | None:
        return cls.parse(environ.get("AGENT_MEMORY_HMAC_KEYS"))
