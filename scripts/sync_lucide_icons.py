"""Regenerate static/orena/kit/icons.js from the official lucide-static release.

The new learner UI (D-088) uses the Lucide icon family at one pinned release.
Every path comes from the package, never typed by hand: the design's own SVGs
are partly hand-typed variants of Lucide icons, so each one was identified by
name and is rendered from the package instead (Design Contract rule 46).

Run it when an icon is added to NAMES or the release is re-pinned:

    python scripts/sync_lucide_icons.py

It downloads the release tarball from the npm registry, reads icons/<name>.svg
for every name below, and writes the inner markup of each into icons.js. CI
never runs it (no network); `scripts/test_orena_kit.mjs` checks the generated
file's header, that every name here is present, and that the new UI only asks
for names that exist.
"""

