SVG = re.compile(r"<svg\b[^>]*>(.*?)</svg>", re.S)


def fetch(release: str) -> dict[str, str]:
    url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{release}.tgz"
    data = urllib.request.urlopen(url, timeout=60).read()
    found: dict[str, str] = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            match = re.fullmatch(r"package/icons/([a-z0-9-]+)\.svg", member.name)
            if not match:
                continue
            svg = tar.extractfile(member).read().decode("utf-8")
            inner = SVG.search(svg).group(1)
            found[match.group(1)] = " ".join(line.strip() for line in inner.strip().splitlines())
    return found


def main() -> int:
    icons = fetch(RELEASE)
    missing = [name for name in NAMES if name not in icons]
    if missing:
        print("not in lucide-static", RELEASE, ":", ", ".join(missing), file=sys.stderr)
        return 1
    body = ",\n".join(f"  {json.dumps(name)}: {json.dumps(icons[name])}" for name in NAMES)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        "/* GENERATED by scripts/sync_lucide_icons.py - do not edit by hand.\n"
        f"   lucide-static@{RELEASE} (ISC licence, https://lucide.dev) - the one icon family of\n"
        "   the learner design (D-088, Design Contract rule 46). Paths are the package's own. */\n"
        f"export const LUCIDE_RELEASE = {json.dumps(RELEASE)};\n\n"
        "export const ICONS = Object.freeze({\n"
        f"{body},\n"
        "});\n\n"
        "/* An icon as inline SVG: 24x24 viewBox, stroke 2, drawn in currentColor. `size` is the\n"
        "   rendered box in px, as the frame gives it. Unknown names throw: an icon the design\n"
        "   uses is added to scripts/sync_lucide_icons.py, never typed here. */\n"
        "export function icon(name, { size = 20, stroke = 2, label = '' } = {}) {\n"
        "  const inner = ICONS[name];\n"
        "  if (!inner) throw new Error(`Unknown icon: ${name}`);\n"
        "  const a11y = label ? `role=\"img\" aria-label=\"${String(label).replace(/\"/g, '&quot;')}\"` : 'aria-hidden=\"true\"';\n"
        "  return `<svg class=\"ic\" width=\"${size}\" height=\"${size}\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"${stroke}\" stroke-linecap=\"round\" stroke-linejoin=\"round\" ${a11y}>${inner}</svg>`;\n"
        "}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(NAMES)} icons from lucide-static@{RELEASE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
