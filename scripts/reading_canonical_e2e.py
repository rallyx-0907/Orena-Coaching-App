"""The canonical Reading live end-to-end run (D-075 §12, D-076) - over HTTP.

Drives a running Orena the way an administrator and a learner would, and
checks each step against what the canonical model promises. It writes real
rows (three articles per language, their approved comprehension sets and, when
learner submit is on, attempts), so it runs against the **admin sandbox
only**: the base URL must be a loopback address on a port other than 8000
(production) and 8010 (preview), and the server must not report itself as
production (`/api/readiness`).

    python scripts/reading_canonical_e2e.py run    --base-url http://localhost:8012 \\
        --state backups/reading-e2e.json [--ai-provider gemini --ai-model gemini-3.5-flash-lite]
    # recreate the runtime: containers down and up, volumes kept
    python scripts/reading_canonical_e2e.py verify --base-url http://localhost:8012 \\
        --state backups/reading-e2e.json

`run`, per learning language (English and Chinese by default):

1. Admin imports three articles, the worker processes them, the Admin reviews
   and publishes them - the publish response and audit carry the rights
   warnings. A set cannot be built before publishing.
2. For each, a comprehension set is generated by the configured AI provider,
   every question decided, the set approved.
3. The learner meets a set without its answers, and the selection policy
   (`/api/reading/practice/next`, what Home's "for you" rail shows) must offer
   an article - the run fails when it offers none. With learner submit off
   (the D-076 default) a submit answers 503 and writes nothing, and the run
   stops there - it proves the gate, not the flow. With submit on:
4. the recommended article is answered first without its recommendation -
   opened some other way - and records no selection; then with the signed
   recommendation `/next` issued, and records the policy's version although
   the evidence moved in between; a request that states provenance itself is
   refused; the next choice moves on;
5. the learner answers an article they picked themselves: the attempt
   persists with no selection recorded, and ability moves;
6. a retried submit (same operation id) returns the same attempt and ability
   moves once;
7. a fresh client (a reload) sees the attempts and the ability unchanged;
8. an edit to the article body stales the set; the attempt is still evidence
   and the set's questions are unchanged;
9. Collection and Learner Summary read the attempt; the cross-skill cue names
   this run's attempt and article; Admin Activity, for this exact account
   (`account_id` from the ability projection), counts exactly this run's
   attempts in this language more than before; product analytics - which by
   design names no learner - counts exactly that many more Reading activities
   and completions than before. The sandbox should have no other learner
   active while it runs.

`verify`, after the runtime is recreated, checks that all of it is still true.

Authentication: with OAuth off (local development) nothing is needed. With it
on, put the signed `writing_coach_session` cookie of an administrator's
session in `ORENA_E2E_SESSION` - the environment, never the command line - and
the learner is that account. Nothing here prints it. The account should have
no pending writing review: the cross-skill cue prefers one to Reading, and the
run reports that rather than passing over it.

Exit status is 0 only when every check passed.
"""
