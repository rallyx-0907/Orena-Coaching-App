export function applyChromeI18n(){
  document.documentElement.lang=uiHtmlLang();

  const textMap={
    '.skip-link':'chrome.skip',
    '[data-route="home"]':'chrome.home',
    '[data-route="write"]':'chrome.write',
    '[data-route="read"]':'chrome.read',
    '[data-route="listen"]':'chrome.listen',
    '[data-route="speak"]':'chrome.speak',
    '[data-route="library"]':'chrome.library',
    '[data-route="grammar"]':'chrome.grammar',
    '[data-route="journey"]':'chrome.journey',
    '[data-route="profile"]':'chrome.profile',
    '[data-account-action="switch"]':'chrome.switch_account',
    '[data-account-action="logout"]':'chrome.sign_out',
  };

  // A destination now appears twice: once in the rail and again in the phone
  // tab bar. querySelector would have translated only whichever came first in
  // the document, leaving the other in English.
  Object.entries(textMap).forEach(([selector,key])=>{
    document.querySelectorAll(selector).forEach(node=>{
      const label=node.querySelector('[data-i18n-label]');
      if(label)label.textContent=t(key);
      else node.textContent=t(key);
    });
  });

  const learnerRole=document.querySelector('[data-account-role]');
  if(learnerRole)learnerRole.textContent=t('chrome.learner');

  const languageLabel=document.querySelector('[data-learning-language-label]');
  if(languageLabel)languageLabel.textContent=t('chrome.interface_language');

  const select=document.getElementById('languageSelect');
  if(select)select.setAttribute('aria-label',t('chrome.interface_language'));

  const account=document.getElementById('accountButton');
  if(account)account.setAttribute('aria-label',t('chrome.account'));

  const close=document.getElementById('dialogClose');
  if(close)close.setAttribute('aria-label',t('chrome.close'));

  const themeButton=document.getElementById('themeButton');
  if(themeButton){
    const label=document.documentElement.dataset.theme==='dark'
      ?t('theme.switch_light')
      :t('theme.switch_dark');
    themeButton.setAttribute('aria-label',label);
    themeButton.title=label;
    const sr=themeButton.querySelector('.sr-only');
    if(sr)sr.textContent=label;
  }

  const dialog=document.getElementById('dialogTitle');
  if(dialog && !dialog.textContent.trim())dialog.textContent=t('chrome.details');
}

