function interpolate(value,vars={}){
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g,(_,key)=>String(vars[key]??''));
}

export function uiLocale(){
  const value=String(supportLanguage()||'');
  return UI_LOCALES.includes(value)?value:'en';
}

export function uiHtmlLang(){
  return uiLocale()==='zh'?'zh-Hans':uiLocale();
}

export function t(key,vars={}){
  const locale=uiLocale();
  const value=COPY[locale]?.[key]??COPY.en[key]??key;
  return interpolate(value,vars);
}

export function localeLabel(value){
  return {
    vi:'Tiếng Việt',
    en:'English',
    zh:'中文',
  }[value]||String(value||'');
}

export function categoryLabel(category='expression'){
  const raw=String(category||'expression').toLowerCase().replaceAll('-','_').replaceAll(' ','_');
  const canonical=CATEGORY_KEYS[raw]||raw;
  const key=`category.${canonical}`;
  const translated=t(key);
  return translated===key?String(category||'').replaceAll('_',' '):translated;
}

