export const speakingCopy = { en, vi, zh };

/* The room's words plus the shared names (the room, the rail) for one interface language. */
export function speakCopy(ui) {
  const own = speakingCopy[ui] || speakingCopy.en;
  const shared = referenceCopy[ui] || referenceCopy.en;
  return { ...own, room: shared.speaking };
}

export const fill = (template, values) =>
  Object.entries(values).reduce((text, [key, value]) => text.replaceAll(`{${key}}`, String(value)), String(template || ''));
