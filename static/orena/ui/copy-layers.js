/* The semantic language layer of every learner copy string (D-079,
   docs/product/ORENA_LANGUAGE_COHERENCE.md). Every key of every learner copy table is declared here -
   there is no default layer: an undeclared key fails scripts/test_orena_copy_layers.mjs.

   interface  a button, a menu item, navigation, a title, a region heading, a label, metadata, a counter,
              a placeholder, a short system status.
   support    a sentence that explains, instructs, hints, coaches; a verdict; feedback on the learner's
              work; the explanation of a result, a state or an error.
   target     learning material. None lives in copy: the material comes from content, not from here.

   A region heading ("WHAT YOU SAID") is interface; a heading that states a result ("1 THING TO FIX",
   "6/6 PASSED") is support; a position counter ("FIX 1 / 3") is interface. REVIEWED lists every key
   whose declared layer differs from the plain rule in scripts/test_orena_copy_layers.mjs (a key named as
   a label stays interface; a sentence of four words or more, a key named like guidance that says
   something, or anything very long is support; the rest is interface), each with the reason a person
   gave. A declaration against that rule without a reason fails the gate. */

