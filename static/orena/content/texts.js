export function importedContent({ title, text, language, id }) {
  if (!EXPLORE_LANGUAGES.includes(language))
    throw new Error('Unsupported content language');
  const body = String(text || '').trim();
  const name = String(title || '').trim();
  if (!name || name.length > 120 || !body || body.length > 12000)
    throw new Error('Invalid imported text');
  return {
    id,
    title: name,
    paragraphs: body.split(/\n\s*\n/),
    origin: 'imported',
    kind: 'personal',
    art: 'personal',
    phrases: [],
    language,
  };
}
